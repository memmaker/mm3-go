// Command adlibdata writes internal/mm3/adlibdata.go: the data of adlib.drv, MM3's AdLib
// driver (its sound effects' scripts and its note table), so the game plays them without
// the driver.
//
//	go run ./cmd/adlibdata GAMEDIR > internal/mm3/adlibdata.go
//
// The scripts are kept in the driver's own format, as the songs are, in one block whose
// calls are rebased to it. It checks that the driver starts in the state the Go port
// assumes, that its channels are the usual operator pairs and that every script decodes
// to commands the port implements, on channels it has, playing only instruments it has
// defined.
package main

import (
	"fmt"
	"log"
	"os"
	"slices"
	"strings"

	"github.com/memmaker/mm3-go/internal/mm3"
)

// Where adlib.drv keeps its data.
const (
	volumes       = 222 // the carriers' level per channel
	frequencies   = 231 // per channel
	musicPrograms = 262 // where each of the 16 instruments is defined, in the song
	sfxPrograms   = 294 // and in the effects' scripts
	modulators    = 387 // each channel's operator slots
	carriers      = 396
	noteTable     = 405
	noteKeys      = 32
	sfxList       = 2407
	channels      = 9
	programs      = 16
	callCommand   = 0
)

// The effect scripts' commands: their argument bytes, -1 for none of the port's.
var argBytes = [16]int{2, 1, 11, 1, 0, 0, 1, 0, 1, 1, 0, 0, 1, 0, 3, 0}

// Which take a channel in their low nibble (the instrument definition takes a slot).
var onChannel = [16]bool{3: true, 6: true, 7: true, 8: true, 9: true, 12: true, 13: true, 14: true}

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: adlibdata GAMEDIR")
	}
	drv, err := mm3.ReadCC(os.Args[1], "adlib.drv")
	if err != nil {
		log.Fatal(err)
	}
	word := func(o int) int { return int(drv[o]) | int(drv[o+1])<<8 }

	for c := range channels {
		if drv[volumes+c] != 0 || word(frequencies+2*c) != 0 {
			log.Fatalf("channel %d does not start cleared", c)
		}
		if mod := c%3 + c/3*8; int(drv[modulators+c]) != mod || int(drv[carriers+c]) != mod+3 {
			log.Fatalf("channel %d's operators are %d and %d", c, drv[modulators+c], drv[carriers+c])
		}
	}
	for i := range 2 * programs * 2 {
		if drv[musicPrograms+i] != 0 {
			log.Fatal("the instruments do not start undefined")
		}
	}

	// the list ends where the first script begins
	var starts []int
	first := len(drv)
	for o := sfxList; o < first; o += 2 {
		starts = append(starts, word(o))
		first = min(first, word(o))
	}
	end := first
	var calls []int // where the call targets are
	seen := map[int]bool{}
	var run func(pc int, defined *[programs]bool, depth int)
	run = func(pc int, defined *[programs]bool, depth int) {
		start := pc
		for {
			if pc < first || pc >= len(drv) {
				log.Fatalf("a script runs out of the block at %d", pc)
			}
			op := int(drv[pc])
			cmd, ch := op/16, op%16
			if onChannel[cmd] && ch >= channels {
				log.Fatalf("command %d at %d on channel %d", op, pc, ch)
			}
			end = max(end, pc+1+argBytes[cmd])
			switch cmd {
			case callCommand:
				if !seen[pc] {
					seen[pc] = true
					calls = append(calls, pc+1)
				}
				if depth == programs {
					log.Fatalf("calls nest too deep at %d", pc)
				}
				run(word(pc+1), defined, depth+1)
			case 2:
				defined[ch] = true
			case 12:
				if p := drv[pc+1]; p >= programs || !defined[p] {
					log.Fatalf("the script at %d plays instrument %d before defining it", start, p)
				}
			case 15:
				return // an end, a return, or a loop to what has run
			}
			pc += 1 + argBytes[cmd]
		}
	}
	for v, s := range starts {
		_ = v
		var defined [programs]bool
		run(s, &defined, 0)
	}

	block := slices.Clone(drv[first:end])
	for _, c := range calls {
		t := word(c) - first
		block[c-first], block[c-first+1] = byte(t), byte(t>>8)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by cmd/adlibdata from adlib.drv; DO NOT EDIT.\n\npackage mm3\n\n")
	fmt.Fprintf(&b, "// adlibKeys is the frequency of each note number's low five bits in block 0: its\n// frequency number, and the block in the bits from the tenth on (the last eight are\n// the words after the table, the driver's jump table).\nvar adlibKeys = [%d]uint16{", noteKeys)
	for i := range noteKeys {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprint(&b, word(noteTable+2*i))
	}
	fmt.Fprintf(&b, "}\n\n// adlibSfx is where each sound effect's script starts in adlibScripts.\nvar adlibSfx = [%d]int{", len(starts))
	for i, s := range starts {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprint(&b, s-first)
	}
	fmt.Fprintf(&b, "}\n\n// adlibScripts are the sound effects' scripts.\nvar adlibScripts = []byte{")
	for i, x := range block {
		if i%24 == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteString(" ")
		}
		fmt.Fprintf(&b, "%d,", x)
	}
	fmt.Fprintf(&b, "\n}\n")
	os.Stdout.WriteString(b.String())
}
