// Command rolanddata writes internal/mm3/rolanddata.go: the data of roland.drv, MM3's
// MT-32 driver (its sound effects' scripts and its note table), so the game plays them
// without the driver.
//
//	go run ./cmd/rolanddata GAMEDIR > internal/mm3/rolanddata.go
//
// It checks that the driver starts in the state the Go port assumes and that every
// script decodes to commands the port implements, on channels it has.
package main

import (
	"fmt"
	"log"
	"os"
	"strings"

	"github.com/memmaker/mm3-go/internal/mm3"
)

// Where roland.drv keeps its data.
const (
	sfxMap     = 67  // the sfx program map, 17 bytes
	musicMap   = 84  // the music's, 17 bytes
	notes      = 237 // the sounding key per channel, 255 none
	velocities = 283
	volumes    = 292
	base       = 303 // added to the songs' call targets
	noteTable  = 330
	noteKeys   = 32
	sfxList    = 2172
	sfxCount   = 151 // sfx 0..150 are started; the list ends where the first script begins
	channels   = 9
)

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: rolanddata GAMEDIR")
	}
	drv, err := mm3.ReadCC(os.Args[1], "roland.drv")
	if err != nil {
		log.Fatal(err)
	}
	word := func(o int) int { return int(drv[o]) | int(drv[o+1])<<8 }

	for c := range channels {
		if drv[notes+c] != 255 || drv[velocities+c] != 127 || drv[volumes+c] != 0 {
			log.Fatalf("channel %d does not start silent at velocity 127 and volume 0", c)
		}
	}
	for i := range 17 {
		if drv[sfxMap+i] != 0 || drv[musicMap+i] != 0 {
			log.Fatal("the program maps do not start cleared")
		}
	}
	if word(base) != 0 {
		log.Fatalf("the songs' base is %d, not 0", word(base))
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by cmd/rolanddata from roland.drv; DO NOT EDIT.\n\npackage mm3\n\n")
	fmt.Fprintf(&b, "// rolandKeys is the key of each note number's low five bits, in the lowest octave\n// (the last eight are the bytes after the table, the driver's jump table).\nvar rolandKeys = [%d]byte{", noteKeys)
	for i := range noteKeys {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprint(&b, drv[noteTable+i])
	}
	fmt.Fprintf(&b, "}\n\n// rolandSfx are the sound effects' scripts; nil plays nothing.\nvar rolandSfx = [%d][]byte{\n", sfxCount)
	for v := range sfxCount {
		start := word(sfxList + 2*v)
		if start >= len(drv) {
			fmt.Fprintf(&b, "\tnil, // %d: the list's entry points past the driver\n", v)
			continue
		}
		script := decode(drv, start, v)
		fmt.Fprintf(&b, "\t{")
		for i, x := range script {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprint(&b, x)
		}
		fmt.Fprintf(&b, "},\n")
	}
	fmt.Fprintf(&b, "}\n")
	os.Stdout.WriteString(b.String())
}

// decode returns sfx v's script at start, up to and including its last byte (an end, or
// 255 to loop), checking each command.
func decode(drv []byte, start, v int) []byte {
	pc := start
	at := func(i int) byte {
		if i >= len(drv) {
			log.Fatalf("sfx %d runs past the driver", v)
		}
		return drv[i]
	}
	for {
		op := at(pc)
		cmd, ch := op>>4, int(op&15)
		pc++
		switch cmd {
		case 15:
			return drv[start:pc]
		case 0, 4, 7, 10, 13, 14:
			if cmd == 4 && ch >= channels {
				log.Fatalf("sfx %d: command %d on channel %d", v, op, ch)
			}
		case 1, 2, 3, 6, 8, 9, 12:
			if cmd != 1 && cmd != 2 && ch >= channels {
				log.Fatalf("sfx %d: command %d on channel %d", v, op, ch)
			}
			at(pc)
			pc++
		case 5:
			if ch >= channels {
				log.Fatalf("sfx %d: command %d on channel %d", v, op, ch)
			}
			at(pc + 3)
			pc += 4
		case 11:
			for at(pc) != 247 {
				pc++
			}
			pc++
		}
	}
}
