"""gends.py DECOMP OUTDIR: generate the Go data segment of mm3-go from the decompilation's own build (one-time
conversion, like the decompilation's tools/mkdata.py; the Go build never runs it).

Inputs, all produced from the decompilation's src/ (never from the original MM3.EXE):
  run/link/MM3.MAP   publics by value: every global's DGROUP address
  run/link/MM3.EXE   our linked build: the initialized DGROUP bytes
  cdecls.py          every global's C type in every translation unit (clang AST)
Outputs: OUTDIR/ds_gen.go (addresses and typed views), OUTDIR/dsinit_gen.go (the initialized data)."""
import json, os, re, subprocess, sys, struct
D, OUT = sys.argv[1], sys.argv[2]
DATA0, DATA1, BSS0, BSS1 = 0x00aa, 0x8724, 0x8d60, 0xf088   # game _DATA (MAIN..MAZEIO) and game _BSS (gbss.asm)
SEG = 0x186f

pubs = []
on = False
for l in open(os.path.join(D, 'run/link/MM3.MAP'), errors='replace'):
    if 'Publics by Value' in l: on = True; continue
    m = re.match(r'\s*186F:([0-9A-F]{4})\s.*\s_(G_\w+)\s*$', l)
    if on and m: pubs.append((int(m.group(1), 16), m.group(2).lower()))
pubs.sort()
exe = open(os.path.join(D, 'run/link/MM3.EXE'), 'rb').read()
hdr = struct.unpack_from('<H', exe, 8)[0] * 16
img = exe[hdr + SEG * 16: hdr + SEG * 16 + 0x10000]
cd = json.loads(subprocess.run([sys.executable, os.path.join(os.path.dirname(__file__), 'cdecls.py'), D],
                               capture_output=True, text=True, check=True).stdout)

STRUCTS = {'chr': ('Chr', 0x12f), 'pc': ('Chr', 0x12f), 'chrat': ('Chr', 0x12f), 'maze': ('Maze', 0x340),
           'map': ('Maze', 0x340), 'spr': ('Spr', 14), 'spr1': ('Spr1', 20), 'dspr': ('Dspr', 32), 'evt': ('Evt', 10),
           'anim': ('Anim', 12), 'mobj': ('Mobj', 12)}
SCALAR = {'unsigned char': ('uint8', 1), 'u8': ('uint8', 1), 'char': ('int8', 1), 'signed char': ('int8', 1),
          'int': ('int16', 2), 'short': ('int16', 2), 'unsigned int': ('uint16', 2), 'unsigned': ('uint16', 2),
          'u16': ('uint16', 2), 'unsigned short': ('uint16', 2), 'long': ('int32', 4), 'unsigned long': ('uint32', 4)}

def parse(t):
    """C type string -> (go elem type, elem size, dims list (first may be None = unsized), kind)"""
    dims = [None if d == '' else int(d, 0) for d in re.findall(r'\[(\w*)\]', t)]
    base = re.sub(r'\s*\[.*$', '', t).strip()
    if '(' in base: return 'Far', 4, dims, 'fptr'      # function pointer (medium model: far)
    if '*' in base:
        pointee = base[:base.rindex('*')]
        return ('Far', 4, dims, 'far') if 'far' in pointee else ('uint16', 2, dims, 'near')
    base = base.replace('far', '').replace('volatile', '').replace('const', '').strip()
    m = re.match(r'struct (\w+)$', base)
    if m:
        g, n = STRUCTS[m.group(1)]
        return g, n, dims, 'struct'
    g, n = SCALAR[base]
    if g == 'int8' and dims: g = 'byte'     # char arrays are text buffers; the C's signed char tests cast
    return g, n, dims, 'scalar'

def choose(name):
    e = cd.get(name)
    if not e: return None
    votes = {}
    for t, files in e['types'].items():
        users = [f for f in files if f != e['defined']]
        w = len(users) * 10 + len(files)
        g, n, dims, k = parse(t)
        if e['defined'] and e['defined'] in files and not users and g in ('uint8', 'byte') and len(e['types']) > 1:
            w = 0   # mkdata's byte array in the defining .inc: the users' type wins
        votes[t] = w
    return max(sorted(votes), key=lambda t: votes[t])

def camel(n):
    p = n.split('_')
    return p[0] + ''.join(x[:1].upper() + x[1:] for x in p[1:])

items = []   # (addr, size, name, ctype)
glob = [(a, n) for a, n in pubs if DATA0 <= a < DATA1 or BSS0 <= a < BSS1]
for i, (a, n) in enumerate(glob):
    end = glob[i + 1][0] if i + 1 < len(glob) and glob[i + 1][0] <= (DATA1 if a < DATA1 else BSS1) else (DATA1 if a < DATA1 else BSS1)
    items.append((a, end - a, n, choose(n)))

out = ['// Code generated by tools/gends.py from the decompilation (MM3.MAP, cdecls.py); DO NOT EDIT.', '',
       'package mm3', '', '// Addresses of the globals in ds (the data segment, DGROUP).', 'const (']
views = []
for a, size, n, t in items:
    out.append('\tadr%s = 0x%04x' % (camel(n)[1:], a))
out.append(')')
out += ['', '// The globals: typed views of ds at their addresses. Arrays run to the end of ds, as C arrays',
        '// do; the comment gives the size up to the next global.', 'var (']
for a, size, n, t in items:
    if t is None:
        g, es, dims, k = 'uint8', 1, [None], 'scalar'; cty = '(asm only)'
    else:
        g, es, dims, k = parse(t); cty = t
    inner = ''.join('[%d]' % d for d in dims[1:] if d)
    esz = es
    for d in dims[1:]:
        if d: esz *= d
    if dims:
        cnt = size // esz if esz else 0
        out.append('\t%s = arr[%s%s](adr%s) // %s, %d' % (camel(n), inner, g, camel(n)[1:], cty, cnt))
    else:
        out.append('\t%s = at[%s](adr%s) // %s' % (camel(n), g, camel(n)[1:], cty))
    views.append((a, size, n, g, es, dims, k))
out.append(')')
open(os.path.join(OUT, 'ds_gen.go'), 'w').write('\n'.join(out) + '\n')

# ---- initialized data
def goq(b):
    s = '"'
    for c in b:
        ch = chr(c)
        if ch == '"': s += '\\"'
        elif ch == '\\': s += '\\\\'
        elif 0x20 <= c < 0x7f: s += ch
        elif c == 10: s += '\\n'
        else: s += '\\x%02x' % c
    return s + '"'

def textlike(b):
    return len(b) >= 2 and b[-1] == 0 and all(c == 0 or 0x20 <= c < 0x7f or c in (10, 11, 13) for c in b) \
        and sum(1 for c in b if 0x20 < c < 0x7f) >= len(b) // 2

def strat(p):
    if DATA0 <= p < DATA1:
        e = img.index(0, p)
        b = img[p:e]
        if all(0x20 <= c < 0x7f or c in (10, 11) for c in b): return goq(b)
    return None

def emit(a, b, name, g, es):
    """Go literal lines for bytes b at address a"""
    if not any(b): return []
    tag = ' // ' + name if name else ''
    if g in ('int16', 'uint16', 'int32', 'uint32', 'Far') and len(b) % es == 0:
        fmt = {2: '<h' if g == 'int16' else '<H', 4: '<i' if g == 'int32' else '<I'}[es]
        vals = [struct.unpack_from(fmt, b, i)[0] for i in range(0, len(b), es)]
        lits = []
        for v in vals:
            s = str(v) if g != 'Far' else '0x%x' % v
            if g == 'uint16' and name and v:      # near pointer tables: show the string they point at
                q = strat(v) if views_by_name.get(name, ('', ''))[1] == 'near' else None
                if q: s = '0x%04x /* %s */' % (v, q[:40] + ('…"' if len(q) > 40 else ''))
            lits.append(s)
        typ = {'int16': 'i16s', 'uint16': 'u16s', 'int32': 'i32s', 'uint32': 'u32s', 'Far': 'u32s'}[g]
        per = 1 if any('/*' in x for x in lits) else 16
        if len(lits) <= per or len(', '.join(lits)) < 80:
            return ['\t{0x%04x, %s{%s}},%s' % (a, typ, ', '.join(lits), tag)]
        rows = [', '.join(lits[i:i + per]) + ',' for i in range(0, len(lits), per)]
        return ['\t{0x%04x, %s{%s' % (a, typ, tag.replace(' // ', ' // ') if tag else '')] + ['\t\t' + r for r in rows] + ['\t}},']
    if textlike(b):
        return ['\t{0x%04x, %s},%s' % (a, goq(b[:-1]), tag)]  # strings get their NUL from the loader
    lits = [str(c) for c in b]
    if len(lits) <= 24:
        return ['\t{0x%04x, []byte{%s}},%s' % (a, ', '.join(lits), tag)]
    return ['\t{0x%04x, []byte{%s' % (a, tag)] + ['\t\t' + ', '.join(lits[i:i + 24]) + ',' for i in range(0, len(lits), 24)] + ['\t}},']

views_by_name = {n: (g, k) for a, size, n, g, es, dims, k in views}
lines = []
marks = sorted([(a, size, n, g, es, k) for a, size, n, g, es, dims, k in views if a < DATA1])
cur = DATA0
def gap(lo, hi):
    """literal pools and statics between globals: NUL-terminated strings where they are text"""
    res, i = [], lo
    while i < hi:
        j = img.index(0, i, hi + 1) + 1 if 0 in img[i:hi] else hi
        b = img[i:j]
        res += emit(i, b, '', 'byte', 1) if b != b'\0' else []
        i = j
    return res
for a, size, n, g, es, k in marks:
    if a > cur: lines += gap(cur, a)
    b = img[a:a + size]
    # a typed global followed by padding/pool in its span: emit the typed part, then the rest as a gap
    lines += emit(a, b, n, g if k != 'struct' else 'byte', es)
    cur = a + size
lines += gap(cur, DATA1)
hdr_lines = ['// Code generated by tools/gends.py from the decompilation (its own build, run/link/MM3.EXE); DO NOT EDIT.',
             '', 'package mm3', '', '// dsInit is the initialized data segment (the C modules\' _DATA): globals in address order,',
             '// the literal pools as strings (each NUL-terminated).', 'var dsInit = []dsBlock{']
open(os.path.join(OUT, 'dsinit_gen.go'), 'w').write('\n'.join(hdr_lines + lines + ['}']) + '\n')

# self-check: replay the blocks and compare with the image
mem = bytearray(0x10000)
joined, acc = [], None
for l in lines:
    if acc is not None:
        acc += ' ' + l.strip()
        if l == '\t}},': joined.append(acc.replace(', }}', '}}').replace(' }},', '},')); acc = None
    elif l.rstrip().endswith('{') or re.match(r'\t\{0x[0-9a-f]+, \w+\{(\[\]byte\{)? //', l) or re.search(r's\{ //|byte\{ //', l):
        acc = re.sub(r' //.*$', '', l)
    else: joined.append(l)
for l in joined:
    l = re.sub(r'\{\s+', '{', l).replace(',}', '}')
    m = re.match(r'\t\{0x([0-9a-f]+), (.*)\},(?: //.*)?$', l)
    a = int(m.group(1), 16); v = m.group(2)
    if v.startswith('"'):
        s = bytes(eval('b' + v.replace('\\x', '\\x')))   # Go and Python agree on these escapes
        mem[a:a + len(s) + 1] = s + b'\0'
    elif v.startswith('[]byte'):
        bb = bytes(int(x) for x in v[7:-1].split(', ')); mem[a:a + len(bb)] = bb
    else:
        typ, body = v.split('{', 1)
        body = re.sub(r'/\*.*?\*/', '', body[:-1])
        fmt = {'i16s': '<h', 'u16s': '<H', 'i32s': '<i', 'u32s': '<I'}[typ]
        vals = [int(x, 0) for x in body.split(',')]
        for i, x in enumerate(vals): struct.pack_into(fmt, mem, a + i * struct.calcsize(fmt), x)
bad = [i for i in range(DATA0, DATA1) if mem[i] != img[i]]
print('globals %d, data lines %d, mismatches %d' % (len(items), len(lines), len(bad)))
if bad: print('first mismatch at %04x' % bad[0]); sys.exit(1)
subprocess.run(['gofmt', '-w', os.path.join(OUT, 'ds_gen.go'), os.path.join(OUT, 'dsinit_gen.go')], check=True)
